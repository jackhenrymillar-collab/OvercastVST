// ColourlessTuning: constants for the "Clear Night" 16-line feedback delay network.
//
// The feedback matrix and the input/output gains were optimised offline so that the
// magnitude response of the (near-)lossless network is as flat as possible, i.e. the tail
// has no tonal colouration or modal ringing, following Dal Santo, Prawda, Schlecht and
// Välimäki, "Differentiable Feedback Delay Network for Colorless Reverberation", DAFx 2023
// (and the 2024 follow-up on optimising small colourless FDNs).
//
// Produced by a numpy/scipy script (optimise_fdn.py, kept outside the repo): matrix
// A = A0 * expm(S - S^T) (orthogonal by construction), unit-norm input and output gains,
// loss = MSE of |H|/rms|H| against 1 on 32768 random frequencies (line gains
// 0.9999^m) + the paper's temporal-density term on sum|A_ij| + a sum-of-fourth-powers
// penalty on matrix entries and gain magnitudes (stops the optimiser routing everything
// through one line, which is "flat" but sparse) + a small L/R-correlation term
// (weights: density 0.5, peak 1.0, corr 0.2); analytic gradients, L-BFGS, best of 2 initialisations
// (winner: hadamard).
//
// Delays are mutually coprime (prime) sample counts at 48 kHz:
//   1201, 1291, 1381, 1493, 1609, 1733, 1861, 2003, 2153, 2311, 2503, 2687, 2887, 3109, 3347, 3607
// delayMs holds them in milliseconds; scale by the sample rate and round.
// matrix is row-major: y[i] = sum_j matrix[i * 16 + j] * x[j]. Orthogonal to ~1e-7.
